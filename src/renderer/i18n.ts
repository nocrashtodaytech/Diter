const dict: Record<Lang, Record<keyof typeof zh, string>> = { zh, 'zh-TW': zhTW, en, ko, ru, ar };
type Key = keyof typeof zh;

let lang: Lang = DEFAULT_LANG;
const subs = new Set<() => void>();

export function getLang(): Lang {
  return lang;
}

export function isValidLang(l: unknown): l is Lang {
  return typeof l === 'string' && (LANGS as string[]).includes(l);
}

export function setLang(l: Lang) {
  if (lang === l) return;
  lang = l;
  subs.forEach((f) => f());
}

export function t(key: Key, vars?: Record<string, string | number>): string {
  let s: string = dict[lang][key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  }
  return s;
}

/** 语言名称显示（用于语言选择器，始终显示各自语言的自称） */
export function langName(l: Lang): string {
  const map: Record<Lang, string> = {
    zh: '简体中文',
    'zh-TW': '繁體中文',
    en: 'English',
    ko: '한국어',
    ru: 'Русский',
    ar: 'العربية',
  };
  return map[l];
}

/** 关于页作者署名（按当前语言） */
export function authorName(l: Lang): string {
  if (l === 'zh') return '今天不宕机';
  if (l === 'zh-TW') return '今天不宕機';
  return 'nocrashtodaytech';
}

/** React hook：订阅语言变化，切换后触发重渲染 */
export function useI18n() {
  const [, force] = useReducer((x: number) => x + 1, 0);
  useEffect(() => {
    subs.add(force);
    return () => {
      subs.delete(force);
    };
  }, []);
  return { t, lang, setLang, getLang };
}
